import { PDFDocument, AFRelationship } from 'pdf-lib';
import type { Invoice } from '../domain/invoice';
import { toCii } from './toCii';
import { renderInvoicePdf } from './renderInvoicePdf';
import { addPdfaOutputIntent } from './pdfa';
import { engine } from './engine';

export interface GenerateFacturxOptions {
  invoice: Invoice;
  /** Custom PDF if mode is FIDÈLE. If not provided, it will generate a visual (GARANTI) */
  sourcePdfBytes?: Uint8Array | undefined;
  iccProfileBytes: Uint8Array;
  fontBytes?: Uint8Array | undefined;
  boldFontBytes?: Uint8Array | undefined;
}

export interface GenerateFacturxResult {
  pdfBytes: Uint8Array;
  xml: string;
  xmlValid: boolean;
  warnings: string[];
}

import { checkPreflight } from './preflight';

export class XmlValidationError extends Error {
  constructor(public messages: string[]) {
    super(`Le XML généré est invalide (XSD/Schematron):\n${messages.join('\n')}`);
    this.name = 'XmlValidationError';
  }
}

export async function generateFacturxDocument(options: GenerateFacturxOptions): Promise<GenerateFacturxResult> {
  const { invoice, sourcePdfBytes, iccProfileBytes, fontBytes, boldFontBytes } = options;
  
  // 1. Generate XML
  const xml = toCii(invoice);

  // 2. Validate XML (STRICT)
  const checkResult = await engine.checkXml(xml, invoice.profile.toLowerCase());
  if (!checkResult.valid) {
    const allErrs = [...(checkResult.errors || []), ...(checkResult.schematronErrors || [])];
    const messages = allErrs.map(m => `[${m.type || 'ERROR'}] ${m.message || JSON.stringify(m)}`);
    throw new XmlValidationError(messages);
  }

  const warnings: string[] = []; // Plus d'avertissement de validation, c'est bloquant

  // 3. Prepare visual PDF
  let doc: PDFDocument;
  let basePdfBytes = sourcePdfBytes;

  if (basePdfBytes) {
    // Mode FIDÈLE : preflight sur le PDF d'origine
    doc = await checkPreflight(basePdfBytes);
  } else {
    // Mode GARANTI : génère depuis zéro
    if (!fontBytes || !boldFontBytes) {
      throw new Error("Fonts are required to generate visual PDF in GARANTI mode.");
    }
    basePdfBytes = await renderInvoicePdf(invoice, fontBytes, boldFontBytes);
    doc = await PDFDocument.load(basePdfBytes);
  }

  // 4. Inject PDF/A OutputIntent
  addPdfaOutputIntent(doc, iccProfileBytes);
  const pdfaBaseBytes = await doc.save();

  // TODO(ci): Intégrer veraPDF dans la pipeline CI pour s'assurer que le document final généré respecte bien la norme PDF/A-3b stricte. 
  // Commande recommandée: verapdf --profile 3b result.pdf

  // 5. Generate final Factur-X (embeds XML + XMP Metadata)
  let finalPdfBytes: Uint8Array;
  try {
    finalPdfBytes = await engine.generateFacturX(pdfaBaseBytes, xml);
  } catch (err: any) {
    if (err.message && err.message.includes('Document ID already set')) {
      // Fallback: This PDF was already generated by the library. 
      // It already has XMP and everything. We just need to replace the XML.
      // (The old XML was removed in preflight.ts).
      // Let's just attach the new XML manually!
      const fallbackDoc = await PDFDocument.load(pdfaBaseBytes);
      const xmlBuffer = new TextEncoder().encode(xml);
      await fallbackDoc.attach(xmlBuffer, 'factur-x.xml', {
        mimeType: 'text/xml',
        description: 'Factur-X XML',
        creationDate: new Date(),
        modificationDate: new Date(),
        afRelationship: AFRelationship.Data
      });
      finalPdfBytes = await fallbackDoc.save();
    } else {
      throw err;
    }
  }

  return {
    pdfBytes: finalPdfBytes,
    xml,
    xmlValid: checkResult.valid,
    warnings
  };
}
